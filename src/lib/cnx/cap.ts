// OASIS CAP 1.2 export of the board's own warnings, and an Atom index.
//
// The board is not an authority: every message is scope=Restricted with a
// restriction naming the official sources, and the sender is the board's own
// address. Element order follows the CAP 1.2 XSD sequences exactly
// (alert → info → area); see cap.test.ts for what is checked.
//
// msgType is deterministic from the stored warning-log snapshot: "Update"
// when the same key held another exported level immediately before (with
// <references> to that message), otherwise "Alert". The identifier hashes the
// level and the forecast peak as they were when the level was entered, so it
// stays the same across requests until the level changes.

import { VERDICT_KEY, type BoardWarning, type WarningLevel } from "./board-warnings";
import type { EntryCore, WarningSnapshot } from "./warning-log-core";

export const CAP_NS = "urn:oasis:names:tc:emergency:cap:1.2";
export const CAP_SENDER = "cap@cnx.nonarkara.org";
export const CAP_RESTRICTION = "Decision support for Chiang Mai Provincial Office. Not an official public warning; official sources: TMD, DDPM.";
export const CAP_LIST_NS = "https://cnx.nonarkara.org/ns/cap-list";
const SENDER_NAME = { th: "ห้องปฏิบัติการเชียงใหม่ (CNX War Room) — เครื่องมือช่วยตัดสินใจ ไม่ใช่หน่วยงานประกาศ", en: "CNX War Room — decision support, not a warning authority" };
const AUDIENCE = { th: "เจ้าหน้าที่เวร สำนักงานจังหวัดเชียงใหม่", en: "Chiang Mai Provincial Office duty officers" };
const NOTE = "Generated by the CNX War Room board from model forecasts and measurements. Official warnings: Thai Meteorological Department (tmd.go.th), DDPM 1784.";
const CIRCLE_RADIUS_KM = 10;
const BANGKOK_OFFSET_MS = 7 * 3_600_000;
const HOUR_MS = 3_600_000;
/** Verdict levels that are exported; an earlier verdict below these was never a CAP message. */
const EXPORTED_VERDICT = new Set(["prepare", "danger"]);

const SEVERITY: Record<WarningLevel, "Minor" | "Moderate" | "Severe"> = { watch: "Minor", alert: "Moderate", critical: "Severe" };

export interface CapMessage {
  identifier: string;
  sent: string;
  msgType: "Alert" | "Update";
  /** "sender,identifier,sent" of the message this one updates. */
  references: string | null;
  effective: string;
  expires: string;
  onset: string | null;
  warning: BoardWarning;
}

/** CAP dateTime: Chiang Mai offset, no fractional seconds, never "Z". */
export function capDateTime(ms: number): string {
  return `${new Date(ms + BANGKOK_OFFSET_MS).toISOString().slice(0, 19)}+07:00`;
}

const capDate = (isoString: string) => capDateTime(Date.parse(isoString));

/** XML text/attribute escape; drops characters XML 1.0 cannot carry. */
export function xmlEscape(s: string): string {
  return s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

async function sha1Hex(s: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-1", new TextEncoder().encode(s));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** `cnx-{domain}-{district}-{sha1(level + peakAt)}` — CAP-safe (no spaces, commas, < or &). */
export async function capIdentifier(key: string, level: string, peakAt: string | null): Promise<string> {
  return `${key}-${await sha1Hex(`${level}${peakAt ?? ""}`)}`;
}

export function isCapIdentifier(v: string): boolean {
  return /^cnx-[a-z0-9-]{1,80}-[0-9a-f]{40}$/.test(v);
}

function wasExported(key: string, prev: EntryCore | null): prev is EntryCore {
  if (!prev) return false;
  return key === VERDICT_KEY ? EXPORTED_VERDICT.has(prev.level) : prev.level !== "none";
}

/** Identifier, timing and msgType for each warning, from the snapshot the log stores. */
export async function capMessages(warnings: readonly BoardWarning[], snapshot: WarningSnapshot, nowMs: number): Promise<CapMessage[]> {
  const hour = Math.floor(nowMs / HOUR_MS) * HOUR_MS;
  return Promise.all(warnings.map(async (w) => {
    const entry = snapshot.entries[w.key];
    const since = entry?.since ?? new Date(hour).toISOString();
    const peakAt = entry ? entry.peakAt : (w.peakAt ?? since);
    const prev = entry?.prev ?? null;
    const updates = wasExported(w.key, prev);
    return {
      identifier: await capIdentifier(w.key, w.boardLevel, peakAt),
      sent: capDate(since),
      msgType: updates ? "Update" : "Alert",
      references: updates ? `${CAP_SENDER},${await capIdentifier(w.key, prev.level, prev.peakAt)},${capDate(prev.since)}` : null,
      effective: capDate(since),
      expires: capDateTime(hour + w.windowHours * HOUR_MS),
      onset: w.peakAt ? capDate(w.peakAt) : null,
      warning: w,
    } satisfies CapMessage;
  }));
}

const tag = (name: string, value: string, pad: string) => `${pad}<${name}>${xmlEscape(value)}</${name}>`;
const pair = (outer: string, valueName: string, value: string, pad: string) =>
  `${pad}<${outer}>\n${tag("valueName", valueName, `${pad}  `)}\n${tag("value", value, `${pad}  `)}\n${pad}</${outer}>`;

function infoXml(m: CapMessage, lang: "th" | "en", web: string, pad: string): string {
  const w = m.warning;
  const p = `${pad}  `;
  const forecast = w.basis === "forecast";
  const area = [
    `${p}<area>`,
    tag("areaDesc", lang === "th" ? w.areaTh : w.areaEn, `${p}  `),
    ...(w.point ? [tag("circle", `${w.point.lat.toFixed(5)},${w.point.lon.toFixed(5)} ${CIRCLE_RADIUS_KM}`, `${p}  `)] : []),
    pair("geocode", "ISO3166-2", "TH-50", `${p}  `),
    `${p}</area>`,
  ];
  return [
    `${pad}<info>`,
    tag("language", lang === "th" ? "th-TH" : "en-US", p),
    tag("category", w.category, p),
    tag("event", lang === "th" ? w.eventTh : w.eventEn, p),
    tag("responseType", w.level === "watch" ? "Monitor" : "Prepare", p),
    tag("urgency", forecast ? "Expected" : "Immediate", p),
    tag("severity", SEVERITY[w.level], p),
    tag("certainty", forecast ? "Possible" : "Observed", p),
    tag("audience", AUDIENCE[lang], p),
    pair("eventCode", "cnx:domain", w.domain, p),
    tag("effective", m.effective, p),
    ...(m.onset ? [tag("onset", m.onset, p)] : []),
    tag("expires", m.expires, p),
    tag("senderName", SENDER_NAME[lang], p),
    tag("headline", lang === "th" ? w.headlineTh : w.headlineEn, p),
    tag("description", lang === "th" ? w.descriptionTh : w.descriptionEn, p),
    tag("instruction", lang === "th" ? w.instructionTh : w.instructionEn, p),
    tag("web", web, p),
    pair("parameter", "cnx:level", w.boardLevel, p),
    pair("parameter", "cnx:value", `${w.value} ${w.unit}`, p),
    pair("parameter", "cnx:provenance", w.provenance, p),
    ...area,
    `${pad}</info>`,
  ].join("\n");
}

/** One CAP <alert> element (no XML declaration). */
export function capAlertXml(m: CapMessage, web: string, pad = ""): string {
  const p = `${pad}  `;
  return [
    `${pad}<alert xmlns="${CAP_NS}">`,
    tag("identifier", m.identifier, p),
    tag("sender", CAP_SENDER, p),
    tag("sent", m.sent, p),
    tag("status", "Actual", p),
    tag("msgType", m.msgType, p),
    tag("source", `CNX War Room board · ${m.warning.domain} · ${m.warning.district}`, p),
    tag("scope", "Restricted", p),
    tag("restriction", CAP_RESTRICTION, p),
    tag("note", NOTE, p),
    ...(m.references ? [tag("references", m.references, p)] : []),
    infoXml(m, "th", web, p),
    infoXml(m, "en", web, p),
    `${pad}</alert>`,
  ].join("\n");
}

const XML_DECL = '<?xml version="1.0" encoding="UTF-8"?>';

/** A single CAP 1.2 document — what a CAP consumer fetches per alert. */
export function capAlertDocument(m: CapMessage, web: string): string {
  return `${XML_DECL}\n${capAlertXml(m, web)}\n`;
}

/**
 * Every active alert in one document. An XML document has one root, so the
 * alerts sit in a thin list element; each child <alert> is a complete CAP 1.2
 * alert. Strict CAP consumers should follow the Atom index to `?id=`.
 */
export function capListDocument(messages: readonly CapMessage[], web: string, generatedAt: string): string {
  const body = messages.map((m) => capAlertXml(m, web, "  ")).join("\n");
  return `${XML_DECL}\n<alerts xmlns="${CAP_LIST_NS}" generated="${xmlEscape(generatedAt)}" count="${messages.length}">\n${body ? `${body}\n` : ""}</alerts>\n`;
}

/** Atom 1.0 (RFC 4287) index, one entry per alert, linking its CAP document. */
export function capAtom(messages: readonly CapMessage[], origin: string, generatedAt: string): string {
  const self = `${origin}/api/cnx/cap.atom`;
  const capUrl = (id: string) => `${origin}/api/cnx/cap.xml?id=${encodeURIComponent(id)}`;
  // The feed changes when a message is sent; with none, it is as of now.
  const updated = messages.length
    ? messages.reduce((latest, m) => (Date.parse(m.sent) > Date.parse(latest) ? m.sent : latest), messages[0].sent)
    : capDate(generatedAt);
  const entries = messages.map((m) => [
    "  <entry>",
    tag("id", capUrl(m.identifier), "    "),
    tag("title", m.warning.headlineEn, "    "),
    tag("updated", m.sent, "    "),
    `    <link rel="alternate" type="application/cap+xml" href="${xmlEscape(capUrl(m.identifier))}"/>`,
    `    <category term="${xmlEscape(m.warning.category)}"/>`,
    tag("summary", `${m.warning.eventEn} · ${m.warning.areaEn} · ${m.msgType} · ${SEVERITY[m.warning.level]}. ${CAP_RESTRICTION}`, "    "),
    "  </entry>",
  ].join("\n"));
  return [
    XML_DECL,
    '<feed xmlns="http://www.w3.org/2005/Atom" xml:lang="en">',
    tag("id", self, "  "),
    tag("title", "CNX War Room — board warnings (CAP 1.2, restricted)", "  "),
    tag("subtitle", CAP_RESTRICTION, "  "),
    tag("updated", updated, "  "),
    `  <author>\n${tag("name", "CNX War Room", "    ")}\n${tag("email", CAP_SENDER, "    ")}\n  </author>`,
    `  <link rel="self" type="application/atom+xml" href="${xmlEscape(self)}"/>`,
    `  <link rel="alternate" type="application/xml" href="${xmlEscape(`${origin}/api/cnx/cap.xml`)}"/>`,
    ...entries,
    "</feed>",
    "",
  ].join("\n");
}
